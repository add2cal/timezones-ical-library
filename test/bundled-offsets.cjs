const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const vm = require('node:vm');
const compiled = esbuild.buildSync({ entryPoints: ['src/bundled-offset.ts'], bundle: true, write: false, platform: 'node', format: 'cjs' });
const moduleObject = { exports: {} };
vm.runInNewContext(compiled.outputFiles[0].text, { module: moduleObject, exports: moduleObject.exports });
const { bundled_model } = moduleObject.exports;
const ny = bundled_model('BEGIN:DAYLIGHT<br>TZOFFSETFROM:-0500<br>TZOFFSETTO:-0400<br>DTSTART:19700308T020000<br>RRULE:FREQ=YEARLY;BYMONTH=3;BYDAY=2SU<br>END:DAYLIGHT<br>BEGIN:STANDARD<br>TZOFFSETFROM:-0400<br>TZOFFSETTO:-0500<br>DTSTART:19701101T020000<br>RRULE:FREQ=YEARLY;BYMONTH=11;BYDAY=1SU<br>END:STANDARD');
assert.ok(ny);
assert.equal(ny.at(Date.parse('2021-03-14T06:59Z')), -18000000);
assert.equal(ny.at(Date.parse('2021-03-14T07:00Z')), -14400000);
assert.equal(ny.wall(Date.parse('2021-03-14T02:30Z')), -14400000);
assert.equal(ny.wall(Date.parse('2021-11-07T01:30Z')), -14400000);
assert.equal(ny.wall(Date.parse('2021-11-07T02:00Z')), -18000000);
const chatham = bundled_model('BEGIN:DAYLIGHT<br>TZOFFSETFROM:+1245<br>TZOFFSETTO:+1345<br>DTSTART:19700927T024500<br>RRULE:FREQ=YEARLY;BYMONTH=9;BYDAY=-1SU<br>END:DAYLIGHT<br>BEGIN:STANDARD<br>TZOFFSETFROM:+1345<br>TZOFFSETTO:+1245<br>DTSTART:19700405T034500<br>RRULE:FREQ=YEARLY;BYMONTH=4;BYDAY=1SU<br>END:STANDARD');
assert.ok(chatham);
assert.equal(chatham.wall(Date.parse('2021-01-01T00:00Z')), 49500000);
assert.equal(chatham.wall(Date.parse('2021-09-26T02:44Z')), 45900000);
assert.equal(chatham.wall(Date.parse('2021-09-26T02:45Z')), 49500000);
assert.equal(bundled_model('BEGIN:STANDARD<br>TZOFFSETFROM:+0545<br>TZOFFSETTO:+0545<br>DTSTART:19700101T000000<br>END:STANDARD').wall(0), 20700000);
assert.equal(bundled_model('garbage'), undefined);
assert.equal(bundled_model('BEGIN:STANDARD<br>TZOFFSETFROM:+0000<br>TZOFFSETTO:+0100<br>DTSTART:19700101T000000<br>RRULE:FREQ=DAILY<br>END:STANDARD'), undefined);
console.log('UTC bundled recurrence evaluator passed');
